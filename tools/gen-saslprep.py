"""Generate RFC 3454/4013 Unicode 3.2 tables from Python's audited stdlib.
Python stringprep and unicodedata tables: PSF license. Generated JS is local-only.
"""
import json, stringprep as sp, unicodedata as ud
from pathlib import Path

def ranges(fn):
    out=[]; start=last=None
    for c in range(0x110000):
        if fn(chr(c)):
            if last is None or c!=last+1:
                if last is not None:out.extend([start,last])
                start=c
            last=c
    if last is not None:out.extend([start,last])
    return out
prohibited=lambda c:any(f(c) for f in [sp.in_table_c12,sp.in_table_c21,sp.in_table_c22,sp.in_table_c3,sp.in_table_c4,sp.in_table_c5,sp.in_table_c6,sp.in_table_c7,sp.in_table_c8,sp.in_table_c9])
tables={k:ranges(f) for k,f in {'unassigned':sp.in_table_a1,'remove':sp.in_table_b1,'space':sp.in_table_c12,'prohibited':prohibited,'randal':sp.in_table_d1,'lcat':sp.in_table_d2}.items()}
corrections={chr(i):ud.ucd_3_2_0.normalize('NFKD',chr(i)) for i in range(0x110000) if not sp.in_table_a1(chr(i)) and ud.ucd_3_2_0.normalize('NFKD',chr(i))!=ud.normalize('NFKD',chr(i))}
body='''// Generated by tools/gen-saslprep.py. RFC4013 SASLprep, Unicode3.2 tables (Python PSF).
(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory();else root.PDF3DSASLprep=factory();})(typeof self!=='undefined'?self:this,function(){
'use strict';
const T=TABLES, corrections=CORRECTIONS;
function has(t,c){let l=0,h=t.length/2-1;while(l<=h){const m=(l+h)>>1;if(c<t[m*2])h=m-1;else if(c>t[m*2+1])l=m+1;else return true;}return false;}
return function prepare(input){
 let mapped='';for(const ch of input){const c=ch.codePointAt(0);if(has(T.unassigned,c))throw Error('Unassigned password character');if(has(T.remove,c))continue;mapped+=has(T.space,c)?' ':corrections[ch]||ch;}
 const s=mapped.normalize('NFKC'), chars=Array.from(s);let randal=false,lcat=false;
 for(const ch of chars){const c=ch.codePointAt(0);if(has(T.prohibited,c)||has(T.unassigned,c))throw Error('Prohibited password character');randal ||= has(T.randal,c);lcat ||= has(T.lcat,c);}
 if(randal&&(lcat||!has(T.randal,chars[0].codePointAt(0))||!has(T.randal,chars[chars.length-1].codePointAt(0))))throw Error('Invalid password directionality');
 return s;
};
});
'''.replace('TABLES',json.dumps(tables,separators=(',',':'))).replace('CORRECTIONS',json.dumps(corrections,separators=(',',':')))
Path(__file__).resolve().parents[1].joinpath('saslprep.js').write_text(body)
